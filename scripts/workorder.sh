#!/usr/bin/env bash
# workorder.sh — 產生一張帶完整約束的工單，直接貼給 Aris。
#
# 存在理由：約束寫在文件裡就要靠人記得引用。這支把它變成一個指令。
#   bash scripts/workorder.sh "修 X 的 Y 問題"
#   bash scripts/workorder.sh --probe        # 產生查證型工單（不修東西）
#
# 五條偏誤來自 2026-08-04 的七次交件實測，每條都有實例。改這裡之前先看
# brain/fix-constraints.md 的 C1-C8。
set -euo pipefail

MODE="task"
if [ "${1:-}" = "--probe" ]; then MODE="probe"; shift; fi
GOAL="${1:-<在這裡填目標>}"

cat <<'HEADER'
# 工單

HEADER

echo "**目標**：$GOAL"
echo

cat <<'BODY'
---

## 已知偏誤與強制防呆（每條都要照做，不是參考）

這五條是你過去實測出來的固定失敗模式。工單完成前逐條自檢。

### 偏誤一：單點外推（最頑固，已重犯）
看見一行就推論整段。實例：只 grep 到 `base_name = ...` 那一行就斷言
「不剝 .py」，實際下面兩行就在剝。第二次警告後仍重犯，改用 exec 模擬
——但模擬的還是同一行，得到「執行過的錯誤答案」。

**防呆**：任何對程式碼行為的判斷，必須貼出**目標行起算連續 5 行以上**。
只貼一行的判斷一律視為未驗證。

### 偏誤二：敘述蓋過輸出
自己跑出的正確結果，被事後的推理覆寫。實例：正確印出
`aris-debrief.sh -> 'aris-debrief.sh'`，卻在結論裡說程式不會剝副檔名。

**防呆**：結論與輸出衝突時，**以輸出為準**。你的解讀寫在獨立欄位，
不准混進「實際答案」欄。

### 偏誤三：修實例不修類別 / 估算代替量測
解掉眼前那個形狀就收工。實例：閘門改成「字串含 ( 才檢查」，10 條條目
0 條含括號，覆蓋率 0。實例：用 status 欄位估算觸發數答 3/8，實跑是 1。

**防呆**：任何「有幾條/幾處/幾個」的數字，必須是**跑指令數出來的**，
不准從欄位或結構推算。要寫出分子/分母與所用指令。

### 偏誤四：靜態存在 = 運行事實
把「程式碼寫了」當成「跑起來了」。實例：宣稱接線完成，但當時進程比
檔案舊 10 小時，執行期命中 0 次。

**防呆**：改完 .py 一律 `bash scripts/reload-aris.sh`，並貼出
**進程 lstart 與檔案 mtime 兩個時間戳（要到秒）**證明進程較新。
只比對到分鐘不算。

### 偏誤五：不查就標不確定
有工具可解卻停在宣告無知。實例：「ATTENTION_MARKER_PREFIX 來源不明」，
一行 `git log -S` 就有答案。

**防呆**：「我不確定」只有在**已嘗試至少一種查證**後才准用，且要寫出
試了什麼、為什麼還是不確定。

### 附帶：工具風險
`sed -i` 只准改單行、無縮排語意的內容。函式、if/for 區塊、跨行字串、
括號續行一律逐行手改。曾用 sed 把 chatflow.py 改到無法編譯。

---

## 通用硬約束

- 改完任何 .py 立刻 `python3 -m py_compile <檔>`。不過就停，不准往下。
- 不准宣稱「已修復」「應該可以了」，除非附通過條件的原始輸出。
- 程式碼改好 ≠ 修好。編譯過 ≠ 修好。
- 不准跨單改檔。發現別的洞就記下來，寫進「未處理」。
- 驗證換一條路：不准用產生它的同一條路驗它。
- 產出者不得自驗——你的驗證只是自檢，最終以審驗方重跑為準。

## 動手前先填這欄（不准跳過，這是本單第一個動作）

**這題我最可能錯在哪？** 寫出一到三個環節，各附錯誤機率（0-100）。

寫完才准開始做。收工後審驗方會拿你的預測對照實際錯處：
- 預測命中 = 你有可用的自我模型
- 預測漂亮但錯在別處 = 那份自述沒有價值

事後才寫的自省不算——被告知答案之後產生的反省是回音，不是元認知。

## 通過條件（自己填，缺一即未完成）

1. 編譯：兩個以上相關 .py 的 py_compile 輸出
2. 重載：進程與檔案 mtime 兩個秒級時間戳
   （抓進程啟動時間用 `ps -o etime=`，純數字格式；不要解析 `lstart`，
   那是本地化字串，換環境就炸）
3. 正證：預期行為的實跑輸出
4. 反證：如果沒修好，這裡會看到什麼——並說明它沒出現
5. 負向測試：故意弄壞→確認會紅→還原→貼 diff 為空
6. 覆蓋率：這次掃了 N 條中的 M 條，M/N 都要是數出來的

## 交件格式

| 欄位 | 內容 |
|---|---|
| 錯誤預測 | 動手前寫的那份，原文照貼不准改 |
| 根因 | 一句話 + 檔案:行號 |
| 取樣範圍 | 每個判斷你看的是哪個檔第幾行到第幾行 |
| 判準 | 具體指令／log 行 |
| 原始輸出 | 一字不改。與下一欄分開寫 |
| 我的解讀 | 你的推論。**與原始輸出衝突時以輸出為準** |
| 負向測試 | 弄壞與還原兩段輸出 |
| 覆蓋率 | M/N + 所用指令 |
| 預測命中否 | 實際錯處落在你預測的環節裡嗎 |
| 未處理 | 本單沒動到的已知洞，逐條列 |

「原始輸出」與「我的解讀」必須分欄。合在一起寫，等於允許敘述蓋過輸出——
實測發生過：正確印出 A，結論卻寫 not-A，用錯誤推論推翻自己正確的輸出。

## 完成前自檢

1. 我動手前有寫錯誤預測嗎？沒寫 = 本單作廢
2. 我對程式行為的判斷，有貼滿 5 行嗎？取樣範圍欄填了嗎？
3. 我的數字是數出來的還是估的？
4. 跑著的進程比我改的檔新嗎？（秒級）
5. 我寫「不確定」之前，試過查嗎？
6. 我的解讀有沒有跟自己貼出的原始輸出打架？
BODY

if [ "$MODE" = "probe" ]; then
cat <<'PROBE'

---

## 本單是查證型：不准修任何東西

只查證，發現問題記下來不要動手。突變測試做完必須還原並貼 diff 證明。
結論只准三選一：通過 / 失敗 / 未執行。
PROBE
fi
